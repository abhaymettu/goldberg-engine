#!/usr/bin/env node
// Writes docs/level-schema.md from the same spec table the validator uses.
// schema-doc            print the doc
// schema-doc --write    rewrite docs/level-schema.md
// schema-doc --check    exit 1 if docs/level-schema.md is out of date
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { WORLD_SPEC, PART_SPECS, GOAL_SPEC } from "../src/schema.js";

const fmtDefault = (v) => (v === undefined ? "" : typeof v === "number" ? String(+v.toFixed(6)) : JSON.stringify(v));
const typeName = (s) => ({ number: "number", int: "integer", string: "string", point: "[x, y]", range: "[min, max]", pitch: "pitch", schedule: "gate list" })[s.kind];
const bounds = (s) => [s.min !== undefined ? `>= ${+s.min.toFixed(6)}` : "", s.max !== undefined ? `<= ${+s.max.toFixed(6)}` : ""].filter(Boolean).join(", ");
const table = (spec) => ["| field | type | required | default | range | meaning |", "|---|---|---|---|---|---|",
  ...Object.entries(spec).map(([k, s]) => `| \`${k}\` | ${typeName(s)} | ${s.required ? "yes" : ""} | ${fmtDefault(s.default)} | ${bounds(s)} | ${s.doc.replace(/\|/g, "\\|")} |`)].join("\n");

export function schemaDoc() {
  return `# Level schema: \`goldberg-level/1\`

Generated by \`node bin/schema-doc.js --write\` from \`src/schema.js\`, the same table the validator reads. Do not edit by hand; \`npm test\` fails if this file is stale.

Units are metres and seconds; angles are degrees, counterclockwise positive. y points up and the origin is the bottom-left corner of the board.

## Top level

\`\`\`json
{
  "schema": "goldberg-level/1",
  "name": "ring-the-bell-easy",
  "notes": "free text, optional",
  "world": { "width": 20, "height": 12, "duration": 8 },
  "goal": { "event": "bell-rung", "part": "bell" },
  "parts": [ { "id": "ball", "type": "ball", "x": 1, "y": 10.6 } ]
}
\`\`\`

| field | required | meaning |
|---|---|---|
| \`schema\` | yes | Must be \`"goldberg-level/1"\` |
| \`name\` | | Free text |
| \`notes\` | | Free text |
| \`world\` | | Physics and board settings, all optional (below) |
| \`goal\` | | What counts as success (below). Without it, \`trace.goal\` is null |
| \`parts\` | yes | List of parts. Every part has \`id\` (letters, digits, \`_\`, \`-\`, starting with a letter, unique) and \`type\` |

Unknown fields anywhere are errors, so a typo never silently falls back to a default. \`validateLevel(json)\` never throws; it returns \`{ ok: true, level }\` with defaults filled in, or \`{ ok: false, errors }\` with one readable string per problem.

## \`world\`

${table(WORLD_SPEC)}

## \`goal\`

${table(GOAL_SPEC)}

The goal is met at the first event matching all given fields. \`trace.goal\` records \`{ met, t, step, event, part, by }\`.

## Parts

${Object.entries(PART_SPECS).map(([type, p]) => `### \`${type}\`\n\n${p.doc}\n\n${table(p.fields)}`).join("\n\n")}

## Events in the trace

Every event carries \`t\` (seconds, \`step * dt\`, rounded to 1e-6) and \`step\` (the fixed step during which it happened). Contact events also carry \`speed\` (approach speed along the contact normal, m/s) and \`point\` ([x, y]). Repeats between the same two parts within \`world.debounce\` are dropped.

| type | extra fields | when |
|---|---|---|
| \`contact\` | \`a\`, \`b\` | Two parts start touching with approach speed >= \`world.contactMinSpeed\` |
| \`bell-rung\` | \`part\`, \`by\` | A part hits a bell at >= the bell's \`minSpeed\` |
| \`bar-hit\` | \`part\`, \`by\`, \`pitch\`, \`midi\`, \`freq\` | A part hits a bar at >= the bar's \`minSpeed\` |
| \`gate-open\`, \`gate-close\` | \`part\` | A hopper gate changes state on its schedule |
| \`out-of-bounds\` | \`part\`, \`point\` | A ball or marble leaves the board (more than 2 m past the left or right edge, or below y = -2) |

Contacts are detected on the state at the start of a step, so a reported time can lead the true touch by at most one \`dt\`.
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const path = fileURLToPath(new URL("../docs/level-schema.md", import.meta.url));
  if (process.argv.includes("--write")) writeFileSync(path, schemaDoc());
  else if (process.argv.includes("--check")) {
    const current = (() => { try { return readFileSync(path, "utf8"); } catch { return ""; } })();
    if (current !== schemaDoc()) { console.error("docs/level-schema.md is stale: run node bin/schema-doc.js --write"); process.exit(1); }
  } else process.stdout.write(schemaDoc());
}
